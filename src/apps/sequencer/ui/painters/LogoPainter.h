#pragma once

#include "core/gfx/Canvas.h"

// The boot identity: PER|FORMER as the thing that already existed, and FLUID MOVEMENT
// as the edition built on top of it.
//
// The wordmark is a rounded geometric display face -- one uniform 4px stroke, round
// terminals, wide counters -- shaded with a vertical chrome ramp and a specular band
// that travels across it while the project loads. That means per-pixel grey values,
// which the design language's three-level rule explicitly exempts brand screens from
// (prep knowledge find brand). Nothing here is ever read under time pressure.
//
// Glyph data is generated by resources/generate-logo.py.
class LogoPainter {
public:
    enum {
        CapHeight = 22,     // height of the wordmark letterforms
        ReflectionRows = 6, // scanlines of mirrored reflection under the baseline
    };

    // Total advance width of `text`: letters, tracking and word spaces. Only the
    // letters of "FLUID MOVEMENT" exist; anything else is skipped. This is a logo
    // renderer, not a font.
    static int wordmarkWidth(const char *text);

    // Chrome wordmark, `CapHeight` tall, drawn down and right from (x, y).
    // `sweep` in [0,1] walks the specular highlight from off the left edge to off the
    // right edge; any value outside that range parks it out of sight.
    static void drawWordmark(Canvas &canvas, int x, int y, const char *text, float sweep);

    // Mirrored, fading reflection of the wordmark, drawn downward from (x, y) --
    // pass the scanline immediately below the wordmark baseline.
    static void drawReflection(Canvas &canvas, int x, int y, const char *text);

    // "PER|FORMER" in Font::Tiny with the divider bar as the bright element.
    // `y` is the text baseline. Returns the advance width.
    static int drawPerformerMark(Canvas &canvas, int x, int y);

    // Font::Tiny caps at a fixed pitch, for letterspaced small type. `y` is the baseline.
    static void drawTrackedText(Canvas &canvas, int x, int y, const char *text, int pitch);
    static int trackedTextWidth(const char *text, int pitch);
};
